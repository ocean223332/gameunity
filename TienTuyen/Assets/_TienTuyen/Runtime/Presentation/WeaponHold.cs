using System.Collections.Generic;
using UnityEngine;

namespace TienTuyen.Presentation
{
    /// <summary>
    /// How a skinned soldier without a weapon clip set holds its firearm in the low-ready and the shouldered aim,
    /// fitted on the hero rig in Blender against measured hand contact and the approved wrist and skin gates
    /// (output/aim-grip/scripts: export_holds.py, then emit_holds_cs.py rewrites the table below).
    /// Body values are character axes (x right, y up, z forward) in hero metres; weapon points and
    /// directions are the model's native axes (x right, y bore, z up) in model units.
    /// </summary>
    internal sealed class WeaponHold
    {
        /// <summary>Hero rig, metres between the shoulder joints: other rigs scale the body and hand offsets by theirs.</summary>
        public const float HeroShoulderWidth = 0.35f;

        public readonly struct Hand
        {
            /// <summary>Wrist joint, and the hand's knuckle and thumb directions, on the weapon.</summary>
            public readonly Vector3 wrist, knuckles, thumb;
            /// <summary>Finger flexion at the proximal and intermediate joints, degrees.</summary>
            public readonly Vector2 curl;
            /// <summary>Thumb: proximal (across the palm, flexion), intermediate (across, flexion), degrees.</summary>
            public readonly Vector4 thumbCurl;

            public Hand(Vector3 wrist, Vector3 knuckles, Vector3 thumb, Vector2 curl, Vector4 thumbCurl)
            {
                this.wrist = wrist; this.knuckles = knuckles; this.thumb = thumb; this.curl = curl; this.thumbCurl = thumbCurl;
            }
        }

        public readonly struct Mode
        {
            /// <summary>Butt plate: from the shoulder-joint midpoint (ready) or the right shoulder joint (aim), chest frame.</summary>
            public readonly Vector3 butt;
            /// <summary>Bore and weapon up: chest frame (ready); character frame before the aim pitch (aim).</summary>
            public readonly Vector3 forward, up;
            /// <summary>Direction each elbow bends away from its shoulder-wrist line, chest frame.</summary>
            public readonly Vector3 rightBend, leftBend;
            public readonly Hand right, left;

            public Mode(Vector3 butt, Vector3 forward, Vector3 up, Vector3 rightBend, Vector3 leftBend, Hand right, Hand left)
            {
                this.butt = butt; this.forward = forward; this.up = up;
                this.rightBend = rightBend; this.leftBend = leftBend; this.right = right; this.left = left;
            }
        }

        public readonly Vector3 grip, support, butt;
        public readonly Mode ready, aim;

        private WeaponHold(Vector3 grip, Vector3 support, Vector3 butt, Mode ready, Mode aim)
        {
            this.grip = grip; this.support = support; this.butt = butt; this.ready = ready; this.aim = aim;
        }

        /// <summary>Native model axes to the weapon root's axes (x bore, y up, z left).</summary>
        public static Vector3 ToRoot(Vector3 native) => new Vector3(native.y, native.z, -native.x);

        /// <summary>The hold for an imported weapon model (Resources/Models name), or null.</summary>
        public static WeaponHold Find(string model) => model != null && Table.TryGetValue(model, out var hold) ? hold : null;

