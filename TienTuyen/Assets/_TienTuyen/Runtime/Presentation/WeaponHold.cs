                    new WeaponHold.Hand(new Vector3(-0.1662f, 0.5091f, 0.1656f), new Vector3(0.9514f, 0.2164f, -0.2192f), new Vector3(-0.2109f, 0.9763f, 0.0486f), new Vector2(74.9f, 87.9f), new Vector4(1.1f, 14.5f, 0.0f, 7.1f))),
